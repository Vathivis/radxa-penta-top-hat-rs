// A compact, one-bit subset of DejaVu Sans Mono, rasterized at the exact
// sizes used by the original Python OLED daemon. Keeping only the characters
// needed by the status pages avoids a runtime font library and a 340 KiB TTF.
// See THIRD_PARTY_LICENSES.md for the DejaVu/Bitstream Vera license notice.

const GLYPH_COUNT: usize = 44;
const GLYPH_COLUMNS: usize = 9;

#[derive(Clone, Copy)]
pub(crate) struct BitmapFont {
    pub(crate) glyph_width: usize,
    pub(crate) advance_64: usize,
    glyphs: &'static [[u16; GLYPH_COLUMNS]; GLYPH_COUNT],
    phased_glyphs: Option<&'static [[[u16; GLYPH_COLUMNS]; 8]; GLYPH_COUNT]>,
}

impl BitmapFont {
    pub(crate) fn glyph(
        self,
        character: char,
        phase_index: usize,
    ) -> &'static [u16; GLYPH_COLUMNS] {
        let glyph_index = glyph_index(character);
        if let Some(glyphs) = self.phased_glyphs {
            &glyphs[glyph_index][phase_index % 8]
        } else {
            &self.glyphs[glyph_index]
        }
    }

    pub(crate) fn text_width(self, character_count: usize) -> usize {
        if character_count == 0 {
            return 0;
        }

        (character_count * self.advance_64).div_ceil(64)
    }

    pub(crate) fn character_x(self, character_index: usize) -> usize {
        character_index * self.advance_64 / 64
    }

    pub(crate) fn phase_index(self, character_index: usize) -> usize {
        ((character_index * self.advance_64) & 63) >> 3
    }
}

fn glyph_index(character: char) -> usize {
    match character {
        ' ' => 0,
        '0'..='9' => 1 + (character as usize - '0' as usize),
        'A'..='Z' => 11 + (character as usize - 'A' as usize),
        '.' => 37,
        ':' => 38,
        '/' => 39,
        '%' => 40,
        '-' => 41,
        '_' => 42,
        '?' => 43,
        _ => 43,
    }
}

